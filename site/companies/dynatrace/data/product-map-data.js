const ref = (id, locator, role="supporting", scope="product-level") => ({id,locator,role,scope});

function makeAssessment(rationale, confidence, sourceId, locator, role="supporting", scope="product-level") {
  return {
    rationale,
    confidence,
    asOf:"2026-08-13",
    sources:[ref(sourceId, locator, role, scope)],
  };
}

function product(config) {
  const maturityConfidence = config.maturityConfidence || "medium";
  const positionConfidence = config.positionConfidence || "low";
  const momentumConfidence = config.momentumConfidence || "low";
  const moatConfidence = config.moatConfidence || "low";
  const sourceId = config.sourceId || "dynatrace-10k-fy2026";
  const sourceLocator = config.sourceLocator || "The Dynatrace Platform";
  const sourceScope = config.sourceScope || "product taxonomy and capability";
  const momentumSource = config.momentumSource || "author-assessment";
  const momentumLocator = config.momentumLocator || "Product-level disclosure gap review";
  const evidenceClaim = config.evidenceClaim || `${config.n} is part of the current Dynatrace product or capability surface.`;

  return {
    id:config.id,
    n:config.n,
    entityType:"product",
    lifecycle:config.lifecycle || "current",
    billing:config.billing || "DPS usage / committed subscription",
    maturity:config.maturity,
    position:config.position,
    momentum:config.momentum || "insufficient",
    moatConviction:config.moatConviction,
    evidenceConfidence:{
      maturity:maturityConfidence,
      position:positionConfidence,
      momentum:momentumConfidence,
      moatConviction:moatConfidence,
    },
    canonicalCategory:config.canonicalCategory,
    suiteMappings:[{suite:config.suite,asOf:"2026-08-13",source:sourceId}],
    monetization:config.monetization || ["usage"],
    motion:config.motion || ["expand","defend"],
    workloads:config.workloads || [],
    moat:config.moat || [],
    dcf:config.dcf || ["usage_growth","nrr","growth_duration"],
    evidenceSignals:config.evidenceSignals || [],
    evidence:[{
      claim:evidenceClaim,
      asOf:"2026-08-13",
      scope:sourceScope,
      sourceClass:SOURCE_REGISTRY[sourceId].sourceClass,
      confidence:maturityConfidence,
      sourceId,
      locator:sourceLocator,
      excerpt:evidenceClaim,
      excerptType:"parsed_summary",
    }],
    assessmentEvidence:{
      maturity:makeAssessment(
        config.maturityRationale || `${config.n} is documented as a current capability, but Dynatrace does not disclose stand-alone product financials.`,
        maturityConfidence,sourceId,sourceLocator,"direct",sourceScope
      ),
      position:makeAssessment(
        config.positionRationale || config.edge,
        positionConfidence,"author-assessment",`Competitive mapping: ${config.n}`,"judgment","competitive position"
      ),
      momentum:makeAssessment(
        config.momentumRationale || "Dynatrace does not provide a product-scoped adoption, revenue, or retention series for this capability.",
        momentumConfidence,momentumSource,momentumLocator,config.momentumSource?"supporting":"limitation","product momentum"
      ),
      moatConviction:makeAssessment(
        config.moatRationale,
        moatConfidence,"author-assessment",`Moat mapping: ${config.n}`,"judgment","switching-cost contribution"
      ),
    },
    moatConvictionRationale:config.moatRationale,
    what:config.what,
    ex:config.ex,
    why:config.why,
    edge:config.edge,
    competitors:config.competitors || [],
    capabilities:config.capabilities || [],
    arr:config.arr || null,
  };
}

